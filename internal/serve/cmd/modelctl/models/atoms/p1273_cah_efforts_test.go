package modelatoms_test

import (
	"os"
	"slices"
	"strings"
	"testing"

	"github.com/PHPCraftdream/rush/internal/agent/provider/cliprovider"
	"github.com/PHPCraftdream/rush/internal/serve/cmd/cli/cmdtest"
	modelatoms "github.com/PHPCraftdream/rush/internal/serve/cmd/modelctl/models/atoms"
	modelopts "github.com/PHPCraftdream/rush/internal/serve/cmd/modelctl/models/opts"
	"github.com/stretchr/testify/require"
)

// Revert-check: generated headers retain provenance; Codex help never uses Claude detection or semantics.
func TestCAHHeadersAndEfforts(t *testing.T) {
	data, err := os.ReadFile("models_cah_gen.go")
	require.NoError(t, err)
	require.True(t, strings.HasPrefix(string(data), "// Code generated by cahsync from cc-arch-hands "+modelatoms.CAHVersionForTest+"; DO NOT EDIT.\n"))
	specs := modelatoms.CAHSpecBySlugForTest()
	var claude, codex, fewest string
	var fewestSpec cliprovider.CLISpec
	for _, code := range modelatoms.SortedCAHCodesForTest() {
		entry, ok := modelatoms.LookupShortCode(code)
		require.True(t, ok)
		spec := specs[entry.Slug]
		switch spec.Binary {
		case "claude":
			if claude == "" {
				claude = code
			}
		case "codex":
			if codex == "" {
				codex = code
			}
			if fewest == "" || len(spec.EffortLevels) < len(fewestSpec.EffortLevels) {
				fewest = code
				fewestSpec = spec
			}
		}
	}
	require.NotEmpty(t, claude)
	require.NotEmpty(t, codex)
	for _, code := range []string{claude, codex, fewest} {
		var err error
		cmd := modelopts.NewEffortsCmd()
		out, _ := cmdtest.CaptureStdoutAndStderr(t, func() { err = cmd.RunE(cmd, []string{code}) })
		require.NoError(t, err)
		entry, ok := modelatoms.LookupShortCode(code)
		require.True(t, ok)
		spec := specs[entry.Slug]
		for _, level := range spec.EffortLevels {
			require.Contains(t, out, "@"+level+" <fast>", code)
		}
		for _, level := range modelatoms.CAHLadderForTest {
			if !slices.Contains(spec.EffortLevels, level) {
				require.NotContains(t, out, "@"+level+" <fast>", code)
			}
		}
		if spec.Binary == "codex" {
			require.Contains(t, out, "model_reasoning_effort")
			require.NotContains(t, out, "Claude")
			require.NotContains(t, out, "claude --help")
		}
	}
}
