#!/usr/bin/env bash
# check_file_size_900_selftest.sh: self-test for
# .githooks/check_file_size_900.sh (the blocking 900-line ratchet for
# the 901..1000 band, sprint 0 stage A1b).
#
# Guard cases build throwaway git repos under the system temp directory
# and run the real guard inside them, asserting:
#   1. a 901-line .go file fails (OVER 900);
#   2. a file at exactly 900 lines passes (boundary: only > max fails);
#   3. a generated-marker file over 900 lines passes (content-based
#      generated detection);
#   4. the ratchet: an allowlisted file at its recorded count passes and
#      grown by one line fails;
#   5. an allowlisted file rewritten to <= 900 lines fails with the
#      "remove it from" message;
#   6. the guard covers .ts files too;
#   7. a stale allowlist entry warns on stderr but does not fail the
#      guard;
#   8. the REAL repository passes with its seeded allowlist.
#
# mktemp -d is deliberately NOT used: this repository's Windows shells
# hand out a virtual /tmp path that child processes cannot resolve, so
# the temp root is built from the standard environment variables, and
# every path below is used in ways (shell redirects, git -C, awk file
# arguments) that survive Windows-style separators. No Windows path is
# ever passed through `awk -v`, whose values undergo backslash-escape
# processing.
set -uo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
guard="$script_dir/check_file_size_900.sh"
allowlist_file="$script_dir/file_size_900_allowlist.txt"

for required in "$guard" "$allowlist_file"; do
	if [ ! -f "$required" ]; then
		printf 'check_file_size_900_selftest.sh: cannot find %s\n' "$required" >&2
		exit 1
	fi
done

tmp_base="${TMPDIR:-${TEMP:-${TMP:-/tmp}}}/check_file_size_900_selftest.$$"
if ! mkdir -p "$tmp_base"; then
	printf 'check_file_size_900_selftest.sh: cannot create %s\n' "$tmp_base" >&2
	exit 1
fi
cleanup() {
	rm -rf -- "$tmp_base" || :
}
trap cleanup EXIT

failures=0

expect_status() {
	desc="$1"
	want="$2"
	got="$3"
	if [ "$got" -eq "$want" ]; then
		printf 'PASS: %s (exit %s)\n' "$desc" "$got"
	else
		printf 'FAIL: %s -- expected exit %s, got %s\n' "$desc" "$want" "$got"
		failures=$((failures + 1))
	fi
}

expect_output_contains() {
	desc="$1"
	got="$2"
	want="$3"
	case "$got" in
	*"$want"*)
		printf 'PASS: %s\n' "$desc"
		;;
	*)
		printf 'FAIL: %s -- output does not contain [%s]\n' "$desc" "$want"
		failures=$((failures + 1))
		;;
	esac
}

# new_repo <n>: fresh throwaway git repo with an empty allowlist; its
# path on stdout, or empty on failure.
new_repo() {
	repo="$tmp_base/repo$1"
	rm -rf -- "$repo" || return 1
	if ! mkdir -p "$repo/.githooks"; then
		return 1
	fi
	if ! : >"$repo/.githooks/file_size_900_allowlist.txt"; then
		return 1
	fi
	if ! git -C "$repo" init -q >/dev/null 2>&1; then
		return 1
	fi
	printf '%s' "$repo"
}

# write_filler <path> <lines> [first-line]: a file with exactly <lines>
# lines, optionally starting with a marker line. The path is a shell
# redirect target only -- never an awk -v value (escape processing).
write_filler() {
	awk -v lines="$2" -v first="${3:-}" 'BEGIN {
		if (first != "") {
			print first
			lines--
		}
		for (i = 1; i <= lines; i++) {
			print "filler line " i
		}
	}' >"$1"
}

# run_guard <repo>: runs the guard inside <repo>; leaves combined output
# in $out and the exit status in $status.
run_guard() {
	out="$(cd "$1" && bash "$guard" 2>&1)"
	status=$?
}

# Case 1: an unallowlisted 901-line .go file fails.
repo="$(new_repo 1)"
if [ -z "$repo" ]; then
	printf 'FAIL: case 1: could not create the throwaway repo\n'
	failures=$((failures + 1))
else
	write_filler "$repo/big.go" 901
	(cd "$repo" && git add -A >/dev/null 2>&1)
	run_guard "$repo"
	expect_status "case 1: a 901-line .go file fails" 1 "$status"
	expect_output_contains "case 1: names the file and its count" "$out" "OVER 900: big.go is 901 lines"
fi

# Case 2: the boundary -- exactly 900 lines passes (only > max fails).
repo="$(new_repo 2)"
if [ -z "$repo" ]; then
	printf 'FAIL: case 2: could not create the throwaway repo\n'
	failures=$((failures + 1))
else
	write_filler "$repo/ok.go" 900
	(cd "$repo" && git add -A >/dev/null 2>&1)
	run_guard "$repo"
	expect_status "case 2: a file at exactly 900 lines passes" 0 "$status"
	expect_output_contains "case 2: summary reports no violations" "$out" "1 file(s) checked, 0 generated skipped, 0 allowlisted over 900 lines, max 900"
fi

# Case 3: a generated-marker file over 900 lines passes (content-based
# generated detection), and the summary reports the skip.
repo="$(new_repo 3)"
if [ -z "$repo" ]; then
	printf 'FAIL: case 3: could not create the throwaway repo\n'
	failures=$((failures + 1))
else
	write_filler "$repo/gen.go" 1200 "// Code generated by tool. DO NOT EDIT."
	(cd "$repo" && git add -A >/dev/null 2>&1)
	run_guard "$repo"
	expect_status "case 3: a generated-marker file over 900 lines passes" 0 "$status"
	expect_output_contains "case 3: reports the file as generated" "$out" "1 file(s) checked, 1 generated skipped"
fi

# Case 4: the ratchet -- an allowlisted file at its recorded count
# passes; grown by one line it fails.
repo="$(new_repo 4)"
if [ -z "$repo" ]; then
	printf 'FAIL: case 4: could not create the throwaway repo\n'
	failures=$((failures + 1))
else
	write_filler "$repo/big.go" 950
	printf 'big.go 950\n' >"$repo/.githooks/file_size_900_allowlist.txt"
	(cd "$repo" && git add -A >/dev/null 2>&1)
	run_guard "$repo"
	expect_status "case 4: allowlisted file at its recorded count passes" 0 "$status"

	printf 'filler line extra\n' >>"$repo/big.go"
	(cd "$repo" && git add -A >/dev/null 2>&1)
	run_guard "$repo"
	expect_status "case 4: allowlisted file grown by one line fails" 1 "$status"
	expect_output_contains "case 4: reports the growth against the recorded count" "$out" "RATCHET VIOLATION: big.go grew to 951 lines (allowlist records 950)"
fi

# Case 5: an allowlisted file rewritten to <= 900 lines must be removed
# from the allowlist; keeping the line would silently turn the ratchet
# into an exemption list.
repo="$(new_repo 5)"
if [ -z "$repo" ]; then
	printf 'FAIL: case 5: could not create the throwaway repo\n'
	failures=$((failures + 1))
else
	write_filler "$repo/big.go" 950
	printf 'big.go 950\n' >"$repo/.githooks/file_size_900_allowlist.txt"
	(cd "$repo" && git add -A >/dev/null 2>&1)
	write_filler "$repo/big.go" 899
	(cd "$repo" && git add -A >/dev/null 2>&1)
	run_guard "$repo"
	expect_status "case 5: allowlisted file now at 899 lines fails" 1 "$status"
	expect_output_contains "case 5: names the file and its new count" "$out" "RATCHET CLEANUP: big.go is now 899 lines"
	expect_output_contains "case 5: asks for the allowlist line to be removed" "$out" "remove it from"
fi

# Case 6: the guard covers .ts files too -- an unallowlisted 905-line
# .ts file fails; allowlisted at its exact count, it passes.
repo="$(new_repo 6)"
if [ -z "$repo" ]; then
	printf 'FAIL: case 6: could not create the throwaway repo\n'
	failures=$((failures + 1))
else
	write_filler "$repo/big.ts" 905
	(cd "$repo" && git add -A >/dev/null 2>&1)
	run_guard "$repo"
	expect_status "case 6: a 905-line .ts file fails" 1 "$status"
	expect_output_contains "case 6: names the file and its count" "$out" "OVER 900: big.ts is 905 lines"

	printf 'big.ts 905\n' >"$repo/.githooks/file_size_900_allowlist.txt"
	run_guard "$repo"
	expect_status "case 6: the .ts file allowlisted at its exact count passes" 0 "$status"
	expect_output_contains "case 6: summary reports the kept entry" "$out" "1 allowlisted over 900 lines"
fi

# Case 7: a stale allowlist entry (path no longer tracked) warns on
# stderr but does not fail the guard.
repo="$(new_repo 7)"
if [ -z "$repo" ]; then
	printf 'FAIL: case 7: could not create the throwaway repo\n'
	failures=$((failures + 1))
else
	write_filler "$repo/ok.go" 100
	printf 'gone.go 901\n' >"$repo/.githooks/file_size_900_allowlist.txt"
	(cd "$repo" && git add -A >/dev/null 2>&1)
	run_guard "$repo"
	expect_status "case 7: a stale allowlist entry does not fail the guard" 0 "$status"
	expect_output_contains "case 7: emits the stale-entry warning" "$out" "warning: stale allowlist entries (path no longer tracked; delete the line):"
	expect_output_contains "case 7: names the stale path" "$out" "  gone.go 901"
fi

# Case 8: the real repository passes with its seeded allowlist.
out="$(bash "$guard" 2>&1)"
status=$?
expect_status "case 8: guard run on the real repository exits 0" 0 "$status"
expect_output_contains "case 8: reports all 23 seeded allowlist entries" "$out" "23 allowlisted over 900 lines, max 900"

if [ "$failures" -gt 0 ]; then
	printf 'check_file_size_900_selftest: %d failure(s)\n' "$failures"
	exit 1
fi
printf 'check_file_size_900_selftest: all cases passed\n'
exit 0
