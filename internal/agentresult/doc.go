// Package agentresult реализует ограниченный профиль JSON Schema 2020-12.
// DecodeSpec проверяет входную спецификацию и компилирует её на этапе admission;
// Compile отдельно компилирует программную Spec для конкретного вызова, а
// Compiled.Validate проверяет полный текст кандидата. Диагностики schema
// mismatch строятся доверенным структурным обходом кандидата по
// скомпилированной схеме и известны только schema-known имена properties.
// Регулярные выражения
// используют Go RE2, а не ECMAScript. Числа проверяются через десятичный
// round-trip float64 и safe-integer предел; целые числа допускаются только до
// 9007199254740991 включительно, в том числе в эквивалентной десятичной или
// экспоненциальной записи, если точный десятичный round-trip сохранён. Это
// ограниченный профиль, а не полная реализация JSON Schema. Внутренне только
// шесть ограничений размеров (minItems/maxItems, minProperties/maxProperties и
// minLength/maxLength) ограничиваются значением min(исходное, B+1), где
// B = MaxCandidateBytes = 1 MiB. Для любого кандидата размером не более B байт
// число элементов, свойств и кодовых точек N не превосходит B. Поэтому при
// исходном лимите больше B максимум после замены на B+1 всегда выполнен
// (N <= B < B+1), а минимум невозможен (N <= B < B+1); поведение сохраняется.
// Остальные числа и имена свойств не ограничиваются этим преобразованием.
// Полный кандидат ограничен 1 MiB. Пакет не обращается к сети.
//
// Контракт диагностики schema mismatch (provenance): текст ошибки библиотеки
// валидации не разбирается никогда; фактом нарушения остаётся только сам
// факт возврата ошибки. Указатели (schema_pointer и instance_pointer) в
// Feedback попадают исключительно из доверенного набора, сформированного
// структурным валидатором: Diagnostic из ValidationError должен точно
// совпадать по значению с доверенным элементом того же индекса — мутация,
// перестановка, добавление или конструирование снаружи ведут к пустым
// указателям. Индексы массивов структурны и разрешены; неизвестные ключи
// кандидата (включая ключи additionalProperties) не раскрываются. После
// скрытого ключа или переполнения лимита путь остаётся неизвестным, его нельзя
// заново продолжить от корня именами потомков. Значения
// кандидата (текст ошибки и сами данные) не попадают в диагностики: reason
// берётся из фиксированного allowlist по коду, исключение — required, где
// schema-known имя добавляется в reason (до 64 рун, без control-байтов).
// Лимиты: не более 8 диагностик, суммарный feedback не более 4 KiB; при
// переполнении диагностики сбрасываются до безопасного fallback.
